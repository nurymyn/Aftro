const frames = [...document.querySelectorAll(".frame")];
const tabs = [...document.querySelectorAll(".screen-nav button")];
const finishCards = [...document.querySelectorAll("[data-finish]")];
const comparison = document.querySelector("#comparison");
const reveal = document.querySelector("#reveal");
const afterImage = document.querySelector("#after-image");
const selectedFinish = document.querySelector("#selected-finish");
const selectedMaterials = document.querySelector("#selected-materials");
const saveStatus = document.querySelector("#save-status");
const scene = document.querySelector("#camera-scene");
const cameraNext = document.querySelector("#camera-next");
const languageSelect = document.querySelector("#language");
const imageClasses = ["room-before", "room-warm", "room-light"];
const materialKeys = { warm: "warmMaterials", light: "lightMaterials" };
const cameraSteps = [
  ["stepOne", "corner", "cornerDetail", "markCorner"],
  ["stepTwo", "direction", "directionDetail", "place"],
  ["complete", "inPlace", "inPlaceDetail", "restart"],
];
const finishKey = "aftro.demo.finish";
const languageKey = "aftro.language";
const catalogMaterials = {};
let catalog = null;
let statusMessage = null;
let activeFinish = "warm";
let cameraStep = 0;

function readPreference(key) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

const preferredLanguage = navigator.languages
  .map((locale) => locale.toLowerCase().split("-")[0])
  .find((locale) => Object.hasOwn(messages, locale));
const savedLanguage = readPreference(languageKey);
let language = Object.hasOwn(messages, savedLanguage) ? savedLanguage : preferredLanguage || "en";

function translate(key, values = {}) {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll("{" + name + "}", value),
    messages[language][key],
  );
}

function materialDescription(slug) {
  const key = materialKeys[slug];
  const provided = catalogMaterials[slug];
  return provided && provided !== messages.en[key] ? provided : translate(key);
}

function navigate(stage, focus = true) {
  const activeFrame = document.getElementById(stage);
  if (!activeFrame?.classList.contains("frame")) return;
  frames.forEach((frame) => frame.classList.toggle("is-active", frame === activeFrame));
  tabs.forEach((tab) => {
    if (tab.dataset.go === stage) tab.setAttribute("aria-current", "step");
    else tab.removeAttribute("aria-current");
  });
  if (focus) {
    activeFrame.scrollIntoView({ block: "nearest" });
    activeFrame.querySelector(".app-bar button")?.focus({ preventScroll: true });
  }
}

function setRoomImage(element, finish) {
  element.classList.remove(...imageClasses);
  element.classList.add("room-" + finish);
}

function updateCamera() {
  const [step, heading, instruction, action] = cameraSteps[cameraStep];
  scene.dataset.step = String(cameraStep);
  setRoomImage(scene, cameraStep === 2 ? activeFinish : "before");
  document.querySelector("#camera-step").textContent = translate(step);
  document.querySelector("#camera-heading").textContent = translate(heading);
  document.querySelector("#camera-instruction").textContent = translate(instruction);
  cameraNext.firstChild.textContent = translate(action) + " ";
}

function updateFinish() {
  selectedFinish.textContent = translate(activeFinish);
  selectedMaterials.textContent = materialDescription(activeFinish);
  setRoomImage(afterImage, activeFinish);
  finishCards.forEach((card) => {
    const slug = card.dataset.finish;
    card.setAttribute("aria-pressed", String(slug === activeFinish));
    card.querySelector("strong").textContent = translate(slug);
    card.querySelector("small").textContent = materialDescription(slug);
  });
  saveStatus.textContent = statusMessage
    ? translate(statusMessage, { finish: translate(activeFinish) })
    : "";
  updateCamera();
}

function selectFinish(slug) {
  if (!Object.hasOwn(materialKeys, slug)) return;
  activeFinish = slug;
  statusMessage = null;
  updateFinish();
}

function updateReveal() {
  comparison.style.setProperty("--reveal", reveal.value + "%");
  reveal.setAttribute("aria-valuetext", translate("sliderValue", {
    before: reveal.value,
    after: 100 - Number(reveal.value),
  }));
}

function updateCatalog() {
  const width = catalog?.width_m ?? 4.5;
  const length = catalog?.length_m ?? 3.6;
  const dimensions = new Intl.NumberFormat(language, { maximumFractionDigits: 3 });
  const area = new Intl.NumberFormat(language, { maximumFractionDigits: 1 });
  document.querySelector("[data-area]").textContent =
    area.format(width * length) + " " + translate("sqMeters");
  document.querySelector("[data-dimensions]").textContent =
    dimensions.format(width) + " × " + dimensions.format(length) + " " + translate("meters");
  document.querySelector("#catalog-status").textContent = translate(catalog ? "liveCatalog" : "demoCatalog");
}

function renderLanguage() {
  document.documentElement.lang = language;
  document.title = translate("title");
  languageSelect.value = language;
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-label]")) {
    element.setAttribute("aria-label", translate(element.dataset.i18nLabel));
  }
  updateReveal();
  updateFinish();
  updateCatalog();
  document.dispatchEvent(new Event("aftro:language"));
}

document.querySelectorAll("[data-go]").forEach((button) => {
  button.addEventListener("click", () => navigate(button.dataset.go, !button.closest(".screen-nav")));
});
finishCards.forEach((card) => {
  card.addEventListener("click", () => selectFinish(card.dataset.finish));
});
reveal.addEventListener("input", updateReveal);
cameraNext.addEventListener("click", () => {
  cameraStep = (cameraStep + 1) % cameraSteps.length;
  updateCamera();
});

document.querySelector("#save-finish").addEventListener("click", async () => {
  const selected = activeFinish;
  const result = await window.aftroAccount?.saveFinish(selected);
  if (result && result !== "guest") {
    if (selected === activeFinish) {
      statusMessage = result;
      updateFinish();
    }
    return;
  }
  try {
    localStorage.setItem(finishKey, selected);
    statusMessage = "savedStatus";
  } catch {
    statusMessage = "storageFailure";
  }
  updateFinish();
});

languageSelect.addEventListener("change", () => {
  if (!Object.hasOwn(messages, languageSelect.value)) return;
  language = languageSelect.value;
  try {
    localStorage.setItem(languageKey, language);
  } catch {
    // The selected language remains active while this tab is open.
  }
  renderLanguage();
});

async function loadCatalog() {
  if (!["http:", "https:"].includes(location.protocol)) return;

  try {
    const response = await fetch("/api/v1/apartments/demo-apartment", {
      headers: { Accept: "application/json" },
    });
    if (!response.ok) return;
    const apartment = await response.json();
    if (!Number.isFinite(apartment.width_m) || !Number.isFinite(apartment.length_m)) return;
    for (const item of apartment.finishes) {
      if (!Object.hasOwn(materialKeys, item.slug)) continue;
      catalogMaterials[item.slug] = item.wall_finish + " · " + item.floor_finish;
    }
    catalog = apartment;
    updateFinish();
    updateCatalog();
  } catch {
    // The design review remains available with the bundled sample.
  }
}

const savedFinish = readPreference(finishKey);
if (Object.hasOwn(materialKeys, savedFinish)) activeFinish = savedFinish;
renderLanguage();
loadCatalog();
